def _comp(p: dict) -> str:
    if p.get("error"):
        return f"- {p['url']} — не вдалося завантажити ({p['error']})"
    hs = "\n".join(f"    {lvl}: {t}" for lvl, t in p["headings"][:45])
    extra = []
    if p.get("faq"):
        extra.append("FAQ: " + " | ".join(p["faq"][:8]))
    if p.get("prices"):
        extra.append("Ціни на сторінці: " + ", ".join(p["prices"][:6]))
    ex = ("\n    " + "\n    ".join(extra)) if extra else ""
    return f"- {p['url']} | {p['type_guess']} | {p['chars']} зн. основного контенту\n{hs}{ex}"


def build_user_prompt(page: dict, project: dict, research: dict) -> str:
    parts = []
    parts.append("## Про компанію / проєкт")
    parts.append(f"Домен: {project.get('domain') or '—'}")
    parts.append(f"Структура URL: RU — {project.get('url_ru_pattern') or 'корінь сайту'}, UA — {project.get('url_ua_pattern') or '/ua/'}")
    if project.get("facts"):
        parts.append("Факти про компанію (можна використовувати): " + project["facts"])
    if project.get("notes"):
        parts.append("Додаткові вимоги до ТЗ: " + project["notes"])
    if page.get("notes"):
        parts.append("Примітка до цієї сторінки: " + page["notes"])
    for lang in ("ru", "ua"):
        kws = page.get(lang) or []
        if not kws:
            parts.append(f"\n## {lang.upper()}: семантики немає")
            continue
        r = research.get(lang, {})
        parts.append(f"\n## {lang.upper()}-версія. Кластер «{page.get('name_' + lang) or ''}»")
        parts.append("Семантика (ключ — частотність): " + "; ".join(f"{k} — {v}" for k, v in kws))
        for s in r.get("serps", []):
            parts.append(f"\n### Видача Google UA за «{s['query']}» (hl={s['lang']})")
            for o in s["organic"]:
                parts.append(f"{o['position']}. {o['url']} — {o['title']}")
            if s.get("paa"):
                parts.append("Люди також питають: " + " | ".join(s["paa"]))
            if s.get("related"):
                parts.append("Пов’язані запити: " + " | ".join(s["related"][:8]))
        if r.get("own_in_serp"):
            parts.append("УВАГА: у видачі є сторінки домену проєкту: " + ", ".join(r["own_in_serp"]))
        parts.append("\n### Розбір сторінок конкурентів (H1–H3, обсяг, FAQ, ціни)")
        parts.extend(_comp(p) for p in r.get("pages", []))
        vs = r.get("volume", {})
        parts.append(f"\nОбсяг основного контенту ТОПу: медіана {vs.get('median')} зн., мін {vs.get('min')}, макс {vs.get('max')}.")
        if r.get("kw_stats"):
            parts.append("Входження ключів у конкурентів (по сторінках): " + "; ".join(
                f"{x['keyword']}: {x['counts']}" for x in r["kw_stats"]))
        if r.get("lsi"):
            parts.append(f"Кандидати LSI (слово | у скількох сторінках | діапазон на цільовий обсяг {r.get('target_chars')} зн.): " + "; ".join(
                f"{x['word']} | {x['docs']} | {x['range']}" for x in r["lsi"]))
    parts.append("\nСклади ТЗ за методикою і передай через submit_tz.")
    return "\n".join(parts)
