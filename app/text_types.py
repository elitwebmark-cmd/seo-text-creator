TRANSITIONS = re.compile(r"^(крім того|окрім того|водночас|утім|втім|ба більше|більше того|також|до того ж|кроме того|вместе с тем|впрочем|более того|также|к тому же)\b", re.I)
YESNO = re.compile(r"^(так|ні|да|нет|тому що|бо|потому что)\b[,.!—\s]", re.I)
OVERUSED = re.compile(r"\b(важлив\w*|ключов\w*|ефективн\w*|комплексн\w*|критичн\w*|важн\w*|ключев\w*|эффективн\w*|комплексн\w*|критичн\w*)", re.I)
RU_SOURCES = re.compile(r"yandex|яндекс|\.ru\b|vk\.com|вконтакт|mail\.ru|wordstat|вордстат|ozon|wildberries|avito|авито|rambler|рамблер", re.I)
OUTDATED = [(re.compile(r"\bFID\b"), re.compile(r"\bINP\b|замін|замен", re.I), "FID замінено на INP — не подавай FID як чинну метрику"),
            (re.compile(r"HowTo", re.I), re.compile(r"прибра|убра|більше не|больше не|скасова|отмен", re.I), "розширені результати HowTo прибрано — не рекомендуй їх"),
            (re.compile(r"FAQPage|розмітк\w* FAQ|разметк\w* FAQ|schema", re.I), None, None)]
AIO = re.compile(r"AI Overview|AI-огляд|огляд\w* від ШІ|ИИ-обзор", re.I)
DURATION = re.compile(r"\b\d+\s*[–-]\s*\d+\s*(тиж|місяц|міс\.|днів|дн\.|рок|недел|месяц|мес\.|дней|лет|год)|\bза\s+\d+\s*(тиж|місяц|днів|недел|месяц|дней)", re.I)
ELIT = re.compile(r"elit[- ]?web|еліт[- ]?веб|элит[- ]?веб", re.I)
SALES = re.compile(r"замовте|замовити (аудит|консультац|послуг)|закажите|заказать (аудит|консультац|услуг)|безкоштовн\w* (консультац|аудит)|бесплатн\w* (консультац|аудит)|залиште заявку|оставьте заявку|зв.яжіться з нами|свяжитесь с нами", re.I)
AI_MENTION = re.compile(r"(створен|написан|згенерован|сгенерирован|написан)\w* (за )?(допомог\w* |помощ\w* )?(ші|штучн|ai|ии|искусствен|нейромереж|нейросет)", re.I)
LINK = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")


def _blocks(md: str):
    """[(kind, text, heading_level)] — 'h', 'p', 'li' у порядку документа."""
    out = []
    for line in md.splitlines():
        l = line.strip()
        if not l or l.startswith("|"):
            continue
        m = re.match(r"^(#{1,6})\s+(.+)$", l)
        if m:
            out.append(("h", m.group(2).strip(), len(m.group(1))))
        elif LIST_RE.match(l):
            out.append(("li", LIST_RE.sub("", l), 0))
        else:
            out.append(("p", l, 0))
    return out


def _sentences(t: str):
    return [x for x in re.split(r"(?<=[.!?…])\s+", t) if x.strip()]


def article_checks(md: str, t: str, kws=(), lang="ua"):
    """(issues, warnings) за правилами редакції для статей; частина — лише для медіа."""
    if not is_article(t):
        return [], []
    issues, warns = [], []
    media = t == MEDIA
    bl = _blocks(md)
    hs = [(lvl, x) for k, x, lvl in bl if k == "h"]
    # заголовки, структура
    in_faq = False
    rhet = []
    prev_head, prev_trans = None, False
    for i, (k, x, lvl) in enumerate(bl):
        if k == "h":
            in_faq = x.strip().upper() == "FAQ" if lvl == 2 else in_faq if lvl > 2 else False
            if media and lvl in (2, 3) and not in_faq and x.rstrip().endswith("?"):
                issues.append(f"Заголовок «{x}»: у медіа H2/H3 пишуться без знака питання")
            if in_faq and lvl == 3 and not x.rstrip().endswith("?"):
                issues.append(f"Питання FAQ «{x}» — має закінчуватися знаком питання")
            prev_head, prev_trans = x, False
            continue
        plain = LINK.sub(r"\1", x).replace("**", "")
        if k == "p":
            if prev_head is not None and not in_faq and YESNO.match(plain):
                issues.append(f"Перше речення після «{prev_head[:50]}» починається з «{plain.split()[0]}» — дай самодостатню відповідь")
            prev_head = None
            tr = bool(TRANSITIONS.match(plain))
            if tr and prev_trans:
                issues.append(f"Два абзаци поспіль починаються зі слів-переходів («{plain[:40]}…») — переходи мають триматися на змісті")
            prev_trans = tr
            if "**" in x and not re.fullmatch(r"\*\*\[[^\]]+\]\*\*", x):
                issues.append(f"Жирний у звичайному абзаці: «{plain[:60]}…» — у абзацах жирного немає")
            if not in_faq:
                rhet += [s for s in _sentences(plain) if s.rstrip().endswith("?")]
        elif k == "li":
            prev_head = None
            if "**" in x and not re.match(r"^\*\*[^*]+\*\*", x):
                issues.append(f"Жирний усередині пункту списку: «{plain[:60]}…» — жирною може бути лише вступна назва пункту")
            if not in_faq:
                rhet += [s for s in _sentences(plain) if s.rstrip().endswith("?")]
        # тире
        for s in _sentences(plain):
            d = len(re.findall(r"(?<!\d)\s[—–]\s|\s—|—\s", s))
            if d > 1:
                issues.append(f"Більше одного тире в реченні: «{s[:90]}…» — поділи речення")
                break
    if rhet:
        issues.append(f"Риторичні питання ({len(rhet)}): «{rhet[0][:80]}» — заміни твердженнями")
    # фінальний розділ і FAQ
    h2 = [x for lvl, x in hs if lvl == 2]
    if media:
        if any(x.strip().upper() == "CTA" for x in h2):
            issues.append("У медіа немає розділу «CTA» — його роль виконує фінальний розділ перед FAQ")
        if h2 and any(x.strip().upper() == "FAQ" for x in h2) and h2[-1].strip().upper() != "FAQ":
            issues.append("FAQ має бути останнім блоком")
        body_h2 = [x for x in h2 if x.strip().upper() not in ("FAQ", "CTA")]
        if body_h2 and FINAL_BAD.match(body_h2[-1].strip()):
            issues.append(f"Фінальний розділ «{body_h2[-1]}» назви за змістом («Що зробити першим», «З чого почати»), а не «Висновок»")
        txt = LINK.sub(r"\1", md)
        if ELIT.search(txt):
            issues.append("Згадка Elit-Web — у медіа її бути не може")
        m = SALES.search(txt)
        if m:
            issues.append(f"Комерційний заклик «{m.group(0)}» — у медіа без закликів замовити")
    # FAQ: «Так/Ні» на початку відповіді
    faq = re.split(r"^##\s+FAQ\s*$", md, flags=re.M | re.I)
    if len(faq) > 1:
        for ans in re.split(r"^###\s+.+$", faq[1], flags=re.M)[1:]:
            a = ans.strip().replace("**", "")
            if YESNO.match(a):
                issues.append(f"Відповідь FAQ починається з «{a.split()[0]}» — почни з короткої суті")
    plain_all = LINK.sub(r"\1", md).replace("**", "")
    # слова-паразити
    words = [w.group(0).lower()[:6] for w in OVERUSED.finditer(plain_all)]
    if len(words) > 6:
        issues.append(f"Слова «важливо / ключовий / ефективний / комплексний / критично» — {len(words)} разів; обмеж до 3–4")
    elif len(words) > 3:
        warns.append(f"Слова «важливо / ключовий / ефективний…» — {len(words)} разів; краще менше")
    # російські джерела й сервіси
    m = RU_SOURCES.search(md)
    if m:
        issues.append(f"Російське джерело чи сервіс («{m.group(0)}») — прибрати")
    # застарілі метрики, розмітка як шлях в AI Overviews
    for s in _sentences(plain_all):
        for rx, ok, msg in OUTDATED:
            if rx.search(s):
                if msg and not (ok and ok.search(s)):
                    issues.append(f"{msg}: «{s[:90]}»")
                elif msg is None and AIO.search(s) and not re.search(r"не потрібн|не нужн|не допомага|не помога|не гарант", s, re.I):
                    issues.append(f"Розмітку не подавай як спосіб потрапити в AI Overviews (Google: спеціальна розмітка не потрібна): «{s[:90]}»")
        if AI_MENTION.search(s):
            issues.append(f"Згадка про створення тексту з допомогою AI: «{s[:80]}»")
    # терміни результату без джерела
    for p in re.split(r"\n\s*\n", md):
        if DURATION.search(p) and not LINK.search(p) and not re.search(r"умовн|условн|для прикладу|для примера", p, re.I):
            m = DURATION.search(p)
            issues.append(f"Термін «{m.group(0)}» без джерела — прибери цифру або дай посилання")
            break
    # кілька ключів в одному абзаці
    if kws:
        from . import norms
        for p in re.split(r"\n\s*\n", md):
            if p.lstrip().startswith("#"):
                continue
            pp = LINK.sub(r"\1", p).replace("**", "")
            hit = [k for k in kws if norms.count(pp, k)]
            if len(hit) >= 3:
                issues.append(f"{len(hit)} ключі в одному абзаці ({', '.join(hit[:3])}) — один запит на абзац")
                break
            if len(hit) == 2:
                warns.append(f"Два ключі в одному абзаці ({', '.join(hit)}) — краще розвести")
    return list(dict.fromkeys(issues)), list(dict.fromkeys(warns))
