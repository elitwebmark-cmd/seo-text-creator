FINAL_BAD = re.compile(r"^(висновок|висновки|підсумок|підсумки|підсумовуючи|заключение|вывод|выводы|итог|итоги|резюме|cta)\b", re.I)


AGENCY_SECTION = re.compile(r"(?=.*(послуг|услуг))(?=.*(\bвід\b|\bот\b|агенц|агентств|що входить|что входит|кошту|стоит|ціни|цены|вартість|стоимость))"
                            r"|чому обирають|почему выбирают|переваги роботи з нами|преимущества работы с нами|наші кейси|наши кейсы", re.I)


def adapt_tz(tz: dict, t: str) -> dict:
    """Медіа: прибрати CTA-блок (його роль виконує фінальний розділ), розділи про послуги/ціни агенції,
    знаки питання в H2/H3; FAQ — останнім. Прибране — у tz["_dropped"]."""
    if t != MEDIA:
        return tz
    import copy
    tz = copy.deepcopy(tz)
    out, skip, dropped = [], False, []
    for b in tz["blocks"]:
        if b[0] == "cta":
            skip = True
            dropped.append("блок CTA (у медіа його роль виконує фінальний розділ)")
            continue
        if b[0] == "h2" and (AGENCY_SECTION.search(b[1]) or AGENCY_SECTION.search(b[2])):
            skip = True
            dropped.append(f"розділ «{b[2] or b[1]}» (послуги / ціни / переваги агенції)")
            continue
        if b[0] in ("h1", "h2", "faq") or (b[0] in ("h3", "q") and not skip):
            skip = False
        if skip:
            continue
        if skip and b[0] == "c":
            continue
        if b[0] in ("h2", "h3"):
            b = (b[0], re.sub(r"\s*\?+\s*$", "", b[1]), re.sub(r"\s*\?+\s*$", "", b[2]))
        out.append(b)
    # FAQ (з питаннями й коментарями) — у кінець
    if any(b[0] == "faq" for b in out):
        i = next(i for i, b in enumerate(out) if b[0] == "faq")
        j = next((k for k in range(i + 1, len(out)) if out[k][0] in ("h1", "h2")), len(out))
        out = out[:i] + out[j:] + out[i:j]
    tz["blocks"] = out
    tz["_dropped"] = dropped
    return tz


