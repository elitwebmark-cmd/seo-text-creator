def detect(tz: dict) -> str:
    """Автовибір: який стиль найкраще пасує темі сторінки (назва, H1, ключі)."""
    parts = [tz.get("name_ua", ""), tz.get("name_ru", ""), tz.get("short", "")]
    parts += [k for l in ("ua", "ru") for k, _ in (tz.get(f"kw_{l}") or [])[:10]]
    parts += [b[1] for b in tz.get("blocks", []) if b and b[0] == "h1" and len(b) > 1]
    text = " ".join(str(p) for p in parts).lower()
    scores = {k: len(re.findall(v["kw"], text)) for k, v in STYLES.items()}
    best = max(scores, key=lambda k: scores[k])
    return best if scores[best] else DEFAULT


